const (
	generatedMarker = "GENERATED by scripts/docs-catalogue"
	screensDir      = "docs/assets/screens"
	errorsPage      = "write/when-something-goes-wrong.md"
	sampleTitle     = "Spring plant sale"
	sampleDate      = "2026-03-02"
)

// catalogue holds the validated packages the pages are built from.
type catalogue struct {
	opts options
	reg  *packages.Registry
	cfg  packages.Configuration
}

func load(o options) (*catalogue, error) {
	reg, findings := packages.Inspect(packages.Roots{Templates: o.templates, Configurations: o.configurations}, "", "")
	if errs := packages.Errors(findings); len(errs) > 0 {
		var b strings.Builder
		for _, f := range errs {
			fmt.Fprintf(&b, "\n  %s", f)
		}
		return nil, fmt.Errorf("the packages do not validate:%s", b.String())
	}
	cfg, ok := reg.Configuration(o.configuration)
	if !ok {
		return nil, fmt.Errorf("configuration %q not found in %s", o.configuration, o.configurations)
	}
	return &catalogue{opts: o, reg: reg, cfg: cfg}, nil
}

// pages returns every generated file, keyed by its path.
func (c *catalogue) pages(out string) (map[string][]byte, error) {
	files := map[string][]byte{}
	names := c.reg.TemplateNames()
	for i, name := range names {
		page, err := c.templatePage(name, i+1, out)
		if err != nil {
			return nil, fmt.Errorf("template %s: %w", name, err)
		}
		files[filepath.Join(out, name+".md")] = []byte(page)
	}
	files[filepath.Join(out, "README.md")] = []byte(c.indexPage(names))
	return files, nil
}

func header(source string) string {
	return fmt.Sprintf("<!-- %s from %s. Do not edit; run `task docs:catalogue`. -->\n\n", generatedMarker, source)
}

func (c *catalogue) indexPage(names []string) string {
	var b strings.Builder
	b.WriteString("---\ntitle: Template catalogue\n---\n\n")
	b.WriteString(header("the packages under templates/"))
	b.WriteString("# Template catalogue\n\n")
	b.WriteString("**Reference.** The Templates that ship with Outprint.\n\n")
	b.WriteString("One page for every Template that ships with Outprint. Each page shows what the\n")
	b.WriteString("result looks like, a block you can copy into a document, every field, and the\n")
	b.WriteString("errors you can expect.\n\n")
	b.WriteString("| Template | Document types |\n|---|---|\n")
	for _, name := range names {
		t, _ := c.reg.Template(name)
		fmt.Fprintf(&b, "| [%s](%s.md) | %s |\n", name, name, codeList(sortedTypes(t)))
	}
	b.WriteString("\nThe pages are generated from the Template packages, so they match this version of Outprint.\n")
	b.WriteString("To add your own Template to the list, see the [Template author guide](../template-author-guide.md).\n")
	return b.String()
}

func (c *catalogue) templatePage(name string, position int, out string) (string, error) {
	t, _ := c.reg.Template(name)
	types := sortedTypes(t)
	previewType := c.previewType(t)
	screen := fmt.Sprintf("template-%s.png", name)
	if _, err := os.Stat(filepath.Join(screensDir, screen)); err != nil {
		return "", fmt.Errorf("preview image %s/%s is missing; run `task docs:catalogue-preview` and commit it", screensDir, screen)
	}
	rel, err := filepath.Rel(out, filepath.Join(screensDir, screen))
	if err != nil {
		return "", err
	}
	intro, err := os.ReadFile(filepath.Join(out, "_"+name+".md"))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "---\ntitle: %s\nsidebar_position: %d\n---\n\n", name, position)
	b.WriteString(header(fmt.Sprintf("templates/%s/manifest.yaml and configurations/%s", name, c.opts.configuration)))
	fmt.Fprintf(&b, "# The %s Template\n\n", name)
	fmt.Fprintf(&b, "**Reference.** The %s Template: its document types, fields and errors.\n\n", name)
	if len(intro) > 0 {
		b.Write(intro)
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "Document types: %s.\n\n", codeList(types))
	fmt.Fprintf(&b, "![First page of a %s set with the %s Template and the example configuration](%s)\n\n", previewType, name, filepath.ToSlash(rel))
	fmt.Fprintf(&b, "The picture is the first page of the `%s` example below, typeset with the real pipeline and the `%s` configuration.\n\n", previewType, c.opts.configuration)
	b.WriteString("To use the Template, a Collection admin binds it to a Collection; see [Configure](../../configure/README.md). ")
	b.WriteString("An author then starts a document with the block below.\n\n")

	for _, typeName := range types {
		section, err := c.typeSection(t, typeName)
		if err != nil {
			return "", fmt.Errorf("document type %s: %w", typeName, err)
		}
		b.WriteString(section)
	}
	return b.String(), nil
}

// previewType is the Document Type of the preview: the Configuration's
// default if the Template has it, else the first by name.
func (c *catalogue) previewType(t packages.Template) string {
	if v, ok := c.cfg.Defaults["document_type"].(string); ok {
		if _, has := t.DocumentTypes[v]; has {
			return v
		}
	}
	return sortedTypes(t)[0]
}

func sortedTypes(t packages.Template) []string {
	names := make([]string, 0, len(t.DocumentTypes))
	for n := range t.DocumentTypes {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func codeList(names []string) string {
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = "`" + n + "`"
	}
	return strings.Join(quoted, ", ")
}

func (c *catalogue) typeSection(t packages.Template, typeName string) (string, error) {
	fields, _ := t.FieldsOf(typeName)
	block, err := c.exampleBlock(t, typeName, fields)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "## Document type `%s`\n\n", typeName)
	b.WriteString("Copy this block to the very start of a document and replace the values. ")
	b.WriteString("Lines that start with `#` are optional: remove the `#` to use them.\n\n")
	b.WriteString("````markdown\n```yaml\n" + block + "```\n````\n\n")

	b.WriteString("### Fields\n\n")
	b.WriteString("Types are explained in [Fill in the document](../../write/fill-in-the-document.md#what-each-kind-of-field-looks-like).\n\n")
	b.WriteString(c.fieldTable(fields))
	b.WriteString(c.fixedTable(fields))

	b.WriteString("### Errors you can expect\n\n")
	b.WriteString("Each message below was produced by the real checker from the mistake shown. ")
	b.WriteString("The code links to its entry in [When something goes wrong](../../" + errorsPage + ").\n\n")
	cases, err := c.errorCases(t, typeName, fields)
	if err != nil {
		return "", err
	}
	b.WriteString("| Message | Cause | Fix |\n|---|---|---|\n")
	for _, ec := range cases {
		fmt.Fprintf(&b, "| %s ([%s](../../%s#%s)) | %s | %s |\n", cell(ec.shown()), ec.code, errorsPage, ec.code, ec.cause, ec.fix)
	}
	b.WriteString("\n")
	return b.String(), nil
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.TrimSpace(s)
}

func (c *catalogue) fieldTable(fields []packages.Field) string {
	var b strings.Builder
	b.WriteString("| Field | Type | Required | Default | Meaning |\n|---|---|---|---|---|\n")
	for _, f := range fields {
		if _, fixed := c.cfg.Fixed[f.Name]; fixed {
			continue
		}
		required := "no"
		if f.Required {
			required = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", f.Name, typeLabel(f), required, defaultLabel(f), cell(meaning(f)))
	}
	b.WriteString("\n")
	var names []string
	for _, f := range fields {
		if v, ok := c.cfg.Defaults[f.Name]; ok {
			names = append(names, fmt.Sprintf("`%s` (%s)", f.Name, scalarText(v)))
		}
	}
	if len(names) > 0 {
		fmt.Fprintf(&b, "The configuration `%s` supplies defaults for %s. A document can override each of them.\n\n", c.opts.configuration, strings.Join(names, ", "))
	}
	return b.String()
}

func (c *catalogue) fixedTable(fields []packages.Field) string {
	var rows []string
	for _, f := range fields {
		if v, fixed := c.cfg.Fixed[f.Name]; fixed {
			rows = append(rows, fmt.Sprintf("| `%s` | %s | %s | %s |", f.Name, typeLabel(f), "`"+scalarText(v)+"`", cell(f.Description)))
		}
	}
	if len(rows) == 0 {
		return ""
	}
	var b strings.Builder
	fmt.Fprintf(&b, "These fields are fixed by the configuration `%s`. A document cannot set them, so they are not in the block.\n\n", c.opts.configuration)
	b.WriteString("| Field | Type | Value | Meaning |\n|---|---|---|---|\n")
	b.WriteString(strings.Join(rows, "\n") + "\n\n")
	return b.String()
}

func typeLabel(f packages.Field) string {
	if f.Type == packages.TypeEnum {
		return "enum (" + strings.Join(f.Values, ", ") + ")"
	}
	return string(f.Type)
}

func meaning(f packages.Field) string {
	m := strings.TrimSpace(f.Description)
	if f.Pattern != "" {
		m += fmt.Sprintf(" Allowed: `%s`.", f.Pattern)
	}
	return m
}

func defaultLabel(f packages.Field) string {
	switch {
	case f.HasDefault:
		return "`" + scalarText(f.Default) + "`"
	case f.Name == "title" || f.Name == "subject":
		return "the Outline title"
	case f.Name == "date":
		return "the last-modified date"
	}
	return "none"
}

// scalarText renders a default or fixed value on one line.
func scalarText(v any) string {
	switch x := v.(type) {
	case []any:
		parts := make([]string, len(x))
		for i, e := range x {
			parts[i] = fmt.Sprint(e)
		}
		return strings.Join(parts, "; ")
	case []string:
		return strings.Join(x, "; ")
	}
	return fmt.Sprint(v)
}

// exampleDocument is the full example of "TEMPLATE[:TYPE]": the block plus a
// short body. The preview image is rendered from it.
func (c *catalogue) exampleDocument(spec string) (string, error) {
	name, typeName, _ := strings.Cut(spec, ":")
	t, ok := c.reg.Template(name)
	if !ok {
		return "", fmt.Errorf("template %q not found", name)
	}
	if typeName == "" {
		typeName = c.previewType(t)
	}
	fields, ok := t.FieldsOf(typeName)
	if !ok {
		return "", fmt.Errorf("template %q has no document type %q", name, typeName)
	}
	block, err := c.exampleBlock(t, typeName, fields)
	if err != nil {
		return "", err
	}
	return "```yaml\n" + block + "```\n" + exampleBody(fields), nil
}

func exampleBody(fields []packages.Field) string {
	body := "Thank you for your enquiry about the spring plant sale. The sale takes place on\n" +
		"**Saturday, 14 March**, starting at *ten o'clock*.\n\n" +
		"- Seedlings and herbs\n- Perennials\n- Garden tools, second hand\n\n" +
		"The layout, the fonts and the colours come from the Template and the\n" +
		"configuration. The text and the details come from you.\n"
	for _, f := range fields {
		if f.Name == "toc" {
			return "## Plan\n\n" + body + "\n## Results\n\nThe sale was a success.\n"
		}
	}
	return body
}
