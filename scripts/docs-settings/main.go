// Command docs-settings generates the settings page of the Reference
// (docs/reference/settings.md) from the registry in internal/settings, the one
// list of environment variables that the packages also use. A page can
// therefore not drift from the code: `-check` regenerates in memory and fails
// if the file on disk differs.
//
// Settings of the advanced tier are listed in a section of their own at the
// end, so the guides and the main part of the page stay short.
//
// Run it from the repository root through `task docs:settings` and
// `task docs:settings-check`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/taskmedia/outprint/internal/settings"
)

type options struct {
	out   string
	check bool
}

func main() {
	var o options
	flag.StringVar(&o.out, "out", "docs/reference/settings.md", "output file")
	flag.BoolVar(&o.check, "check", false, "do not write; fail if the file differs from the registry")
	flag.Parse()
	if err := run(o); err != nil {
		fmt.Fprintf(os.Stderr, "docs-settings: %v\n", err)
		os.Exit(1)
	}
}

func run(o options) error {
	page := []byte(render(settings.All()))
	if o.check {
		return checkDrift(o.out, page)
	}
	if err := os.MkdirAll(filepath.Dir(o.out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(o.out, page, 0o644)
}

func checkDrift(path string, want []byte) error {
	have, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%s: %w; run `task docs:settings`", path, err)
	}
	if !bytes.Equal(have, want) {
		return fmt.Errorf("%s differs from internal/settings; run `task docs:settings` and commit the result", path)
	}
	return nil
}

// render writes the page. Components appear in the order of their first
// setting; the advanced settings follow in a section of their own.
func render(all []settings.Setting) string {
	var b strings.Builder
	b.WriteString(header)
	for _, group := range groupByComponent(all) {
		fmt.Fprintf(&b, "\n## %s\n", group.component)
		for _, s := range group.settings {
			writeSetting(&b, s, false)
		}
	}
	if advanced := advancedSettings(all); len(advanced) > 0 {
		b.WriteString(advancedIntro)
		for _, s := range advanced {
			writeSetting(&b, s, true)
		}
	}
	return b.String()
}

const advancedIntro = `
## Advanced

These settings work, but few installations need them. The image and the Compose
file set what the defaults cannot. Change one only for a reason you can name.
`

const header = `---
sidebar_position: 11
---

<!-- GENERATED by scripts/docs-settings from internal/settings. Do not edit; run ` + "`task docs:settings`" + `. -->

# Settings

**Reference.** The environment variables that configure Outprint, with type, default and effect.

Every setting is an environment variable. The heading above it names the part
that reads it. The PDF action settings go to the Gateway; the injector reads
them too. A setting that is **required** has no usable default: the service
does not start without it. All others work unset.

Some settings override a key of the [service configuration](service-configuration.md),
and the [limits](limits.md) page lists what the size and time limits mean.
`

type group struct {
	component string
	settings  []settings.Setting
}

func groupByComponent(all []settings.Setting) []group {
	var groups []group
	index := map[string]int{}
	for _, s := range all {
		if s.Tier == settings.Advanced {
			continue
		}
		i, ok := index[s.Component]
		if !ok {
			i = len(groups)
			index[s.Component] = i
			groups = append(groups, group{component: s.Component})
		}
		groups[i].settings = append(groups[i].settings, s)
	}
	return groups
}

func advancedSettings(all []settings.Setting) []settings.Setting {
	var out []settings.Setting
	for _, s := range all {
		if s.Tier == settings.Advanced {
			out = append(out, s)
		}
	}
	return out
}

func writeSetting(b *strings.Builder, s settings.Setting, showComponent bool) {
	required := "no"
	if s.Tier == settings.MustSet {
		required = "yes"
	}
	def := s.Default
	if def == "" {
		def = "none"
	}
	part := ""
	if showComponent {
		part = fmt.Sprintf(" **Read by:** %s.", s.Component)
	}
	fmt.Fprintf(b, "\n### `%s`\n\n**Type:** %s. **Required:** %s. **Default:** %s.%s\n\n%s\n",
		s.Name, s.Type, required, def, part, s.Description)
}
