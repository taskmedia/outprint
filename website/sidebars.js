// Sections, one folder each under docs/ (issue #52). Every folder has an
// intro page (README.md) that is the section's link in the sidebar. Internals
// (docs/internals) and the decision records (docs/adr) are on GitHub only and
// are not in the sidebar. They are not excluded from the build: a released
// version still carries them in its own sidebar, and excluding them would
// break that version's build (website/scripts/docs-versions.mjs prunes old
// docs with the current exclude list). Research is excluded as before.
//
// The landing page is website/src/pages/index.js. docs/README.md is the plain
// table for GitHub and is not published (see docusaurus.config.js).

/** @param {string} label @param {string} dir @param {object[]} [more] */
const section = (label, dir, more = []) => ({
  type: 'category',
  label,
  collapsed: false,
  link: {type: 'doc', id: `${dir}/README`},
  items: [{type: 'autogenerated', dirName: dir}, ...more],
});

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  docs: [
    section('Write', 'write'),
    section('Install', 'install'),
    // One page: the section is that page.
    {type: 'doc', id: 'configure/README', label: 'Configure'},
    section('Templates', 'templates'),
    section('Reference', 'reference'),
  ],
};

module.exports = sidebars;
