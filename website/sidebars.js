// Five sections, one folder each under docs/ (issue #52). Every folder has an
// intro page (README.md) that is the section's link in the sidebar. The
// decision records live in docs/adr, next to their index, and are shown
// inside Internals.
//
// The landing page is website/src/pages/index.js. docs/README.md is the plain
// table for GitHub and is not published (see docusaurus.config.js).

/** @param {string} label @param {string} dir @param {object[]} [more] */
const section = (label, dir, more = []) => ({
  type: 'category',
  label,
  collapsed: false,
  link: {type: 'doc', id: `${dir}/README`},
  items: [{type: 'autogenerated', dirName: dir}, ...more],
});

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  docs: [
    section('Write', 'write'),
    section('Configure', 'configure'),
    section('Deploy', 'deploy'),
    section('Templates', 'templates'),
    section('Internals', 'internals', [
      {
        type: 'category',
        label: 'Decisions',
        link: {type: 'doc', id: 'adr/README'},
        items: [{type: 'autogenerated', dirName: 'adr'}],
      },
    ]),
  ],
};

module.exports = sidebars;
