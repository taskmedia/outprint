// Tests for docs-versions.mjs against a throwaway git repository.
//   npm test   (node --test scripts/)
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {afterEach, beforeEach, describe, it} from 'node:test';

import {materializeVersions, pickRef, releasedMinors} from './docs-versions.mjs';

const EXCLUDE = ['README.md', 'sanitize.md', 'assets/**'];

describe('releasedMinors', () => {
  it('keeps only X.Y.0 tags, newest first, compared as numbers', () => {
    const tags = ['v0.9.0', 'v0.10.0', 'v0.9.1', 'v0.10.0-rc.1', 'v1.0.0', 'latest', 'v0.2.0'];
    assert.deepEqual(releasedMinors(tags), ['1.0', '0.10', '0.9', '0.2']);
  });

  it('is empty without release tags', () => {
    assert.deepEqual(releasedMinors(['v0.1.0-rc.1', 'nightly']), []);
  });
});

describe('pickRef', () => {
  it('prefers the correction branch over the tag', () => {
    assert.equal(pickRef('0.1', ['docs-release/0.1', 'docs-release/0.2']), 'docs-release/0.1');
  });

  it('falls back to the tag vX.Y.0', () => {
    assert.equal(pickRef('0.1', ['docs-release/0.2']), 'v0.1.0');
  });
});

describe('materializeVersions', () => {
  let repo;
  let site;

  const git = (...args) => execFileSync('git', ['-C', repo, ...args], {encoding: 'utf8'});
  const write = (file, text) => {
    mkdirSync(dirname(join(repo, file)), {recursive: true});
    writeFileSync(join(repo, file), text);
  };
  const commit = (message) => {
    git('add', '-A');
    git('-c', 'user.name=t', '-c', 'user.email=t@example.invalid', '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', message);
  };
  const run = () => materializeVersions({repoRoot: repo, siteDir: site, exclude: EXCLUDE});
  const read = (file) => readFileSync(join(site, file), 'utf8');

  beforeEach(() => {
    repo = mkdtempSync(join(tmpdir(), 'docs-versions-'));
    site = join(repo, 'website');
    git('init', '-q', '-b', 'main');
    write('docs/write/page.md', 'released text\n');
    write('docs/README.md', 'github table\n');
    write('docs/sanitize.md', 'repo only\n');
    write('docs/assets/logo/mark.svg', '<svg/>');
    write('docs/assets/screens/shot.png', 'png');
    write('website/sidebars.js', "module.exports = {docs: [{type: 'autogenerated', dirName: 'write'}]};\n");
    commit('release');
    git('tag', 'v0.1.0');
    write('docs/write/page.md', 'text after the release\n');
    commit('after');
  });

  afterEach(() => rmSync(repo, {recursive: true, force: true}));

  it('exports the docs as released, not as they are now', async () => {
    await run();
    assert.equal(read('versioned_docs/version-0.1/write/page.md'), 'released text\n');
  });

  it('lists the versions newest first', async () => {
    write('docs/write/page.md', 'second\n');
    commit('second');
    git('tag', 'v0.2.0');
    git('tag', 'v0.2.1');
    git('tag', 'v0.3.0-rc.1');
    const versions = await run();
    assert.deepEqual(versions, ['0.2', '0.1']);
    assert.deepEqual(JSON.parse(read('versions.json')), ['0.2', '0.1']);
  });

  it('prunes what the site does not publish and keeps the screens', async () => {
    await run();
    const base = 'versioned_docs/version-0.1';
    assert.ok(!existsSync(join(site, base, 'README.md')));
    assert.ok(!existsSync(join(site, base, 'sanitize.md')));
    assert.ok(!existsSync(join(site, base, 'assets/logo')));
    assert.ok(existsSync(join(site, base, 'assets/screens/shot.png')));
  });

  it('writes the sidebar of the tag as JSON', async () => {
    await run();
    assert.deepEqual(JSON.parse(read('versioned_sidebars/version-0.1-sidebars.json')), {
      docs: [{type: 'autogenerated', dirName: 'write'}],
    });
  });

  it('uses the sidebar of the site when the tag has none', async () => {
    git('rm', '-q', 'website/sidebars.js');
    commit('drop sidebar');
    git('tag', 'v0.2.0');
    write('website/sidebars.js', "module.exports = {docs: ['write/page']};\n");
    mkdirSync(site, {recursive: true});
    await run();
    assert.deepEqual(JSON.parse(read('versioned_sidebars/version-0.2-sidebars.json')), {docs: ['write/page']});
  });

  it('takes the correction branch instead of the tag', async () => {
    git('branch', 'docs-release/0.1', 'v0.1.0');
    git('switch', '-q', 'docs-release/0.1');
    write('docs/write/page.md', 'corrected\n');
    commit('fix a typo');
    git('switch', '-q', 'main');
    await run();
    assert.equal(read('versioned_docs/version-0.1/write/page.md'), 'corrected\n');
  });

  it('fails when the ref has no docs', async () => {
    git('rm', '-rq', 'docs');
    commit('no docs');
    git('tag', 'v0.2.0');
    await assert.rejects(run(), /v0\.2\.0.*docs/s);
  });

  it('writes nothing and removes stale output without release tags', async () => {
    git('tag', '-d', 'v0.1.0');
    mkdirSync(join(site, 'versioned_docs/version-0.0'), {recursive: true});
    writeFileSync(join(site, 'versions.json'), '["0.0"]');
    const versions = await run();
    assert.deepEqual(versions, []);
    assert.ok(!existsSync(join(site, 'versions.json')));
    assert.ok(!existsSync(join(site, 'versioned_docs')));
  });
});
